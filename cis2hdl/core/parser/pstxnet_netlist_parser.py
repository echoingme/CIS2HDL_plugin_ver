"""PstxnetNetlistParser — parse OrCAD pstxnet.dat EXPANDEDNETLIST files.

The pstxnet.dat file is generated by OrCAD Capture's PSTWRITER and contains
the netlist connectivity data in EXPANDEDNETLIST format.  It maps each
reference designator's pin number to its connected net name.

This data is used to supplement pin connections for instances that lack
net connectivity from DSN or EDIF sources.

Format example::

    NET_NAME 'CLK2SLAVE_OUTN_5G'
    NODE_NAME C361 2
    NODE_NAME R229 2

Usage::

    from cis2hdl.core.parser.pstxnet_netlist_parser import PstxnetNetlistParser
    parser = PstxnetNetlistParser()
    netlist_map = parser.parse(Path("pstxnet.dat"))
    # netlist_map["C361"]["2"] → "CLK2SLAVE_OUTN_5G"
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass, field
from pathlib import Path

logger = logging.getLogger(__name__)


# ============================================================
#  PstxnetConnection — parsed node from pstxnet.dat
# ============================================================


@dataclass
class PstxnetConnection:
    """A single node connection from EXPANDEDNETLIST.

    Attributes:
        refdes: Reference designator (e.g. "C361", "R229").
        pin_number: Pin number on the component (e.g. "2").
        net_name: Net name the pin connects to (e.g. "CLK2SLAVE_OUTN_5G").
    """

    refdes: str = ""
    pin_number: str = ""
    net_name: str = ""


# ============================================================
#  Regex patterns (compiled once at module level)
# ============================================================

# State constants
_IDLE = 0
_IN_NET_HEADER = 1   # Saw "NET_NAME", waiting for quoted name on next line
_IN_NET = 2          # Have net_name, collecting NODE_NAMEs
_IN_NODES = 3

# Matches: NET_NAME (alone, net name is on next line in quotes)
_RE_NET_NAME_HEADER = re.compile(r"^\s*NET_NAME\s*$")

# Matches: Quoted net name on its own line: 'CLK2SLAVE_OUTN_5G'
_RE_QUOTED_NAME = re.compile(r"^\s*'([^']+)'\s*[:;]?\s*$")

# Matches: NODE_NAME C361 2
_RE_NODE_NAME = re.compile(r"^\s*NODE_NAME\s+(\S+)\s+(\S+)\s*$")

# Lines to skip — must cover ALL net attribute keywords.  Missing any one
# (e.g. RELATIVE_PROPAGATION_DELAY) makes the state machine treat that line
# as the end of the current net, silently dropping every following NODE_NAME.
_RE_SKIP_LINE = re.compile(
    r"^\s*(?:{|--|@|C_SIGNAL|DIFFERENTIAL_PAIR|C_PATH|P_PATH|SECTION_NUMBER|"
    r"NET_PHYSICAL_TYPE|NET_SPACING_TYPE|RELATIVE_PROPAGATION_DELAY|RATSNEST_SCHEDULE)"
)


# ============================================================
#  PstxnetNetlistParser
# ============================================================


class PstxnetNetlistParser:
    """Parser for OrCAD pstxnet.dat EXPANDEDNETLIST files.

    Uses a state-machine approach to parse NET_NAME / NODE_NAME blocks.

    State flow: IDLE → IN_NET → IN_NODES → IDLE

    Attributes:
        ENCODING: "latin-1" — consistent with other PST parsers.
    """

    ENCODING: str = "latin-1"

    def parse(self, file_path: Path) -> dict[str, dict[str, str]]:
        """Parse a pstxnet.dat file into a refdes → {pin_number: net_name} map.

        If the file does not exist or cannot be parsed, returns an empty
        dict (no exception raised — pstxnet is an optional data source).

        Args:
            file_path: Path to the pstxnet.dat file.

        Returns:
            dict mapping refdes → {pin_number: net_name}.
        """
        if not file_path.exists():
            logger.debug("pstxnet file not found: %s — skipping", file_path)
            return {}

        try:
            with open(file_path, "r", encoding=self.ENCODING, errors="replace") as fh:
                content: str = fh.read()
        except (OSError, UnicodeDecodeError) as exc:
            logger.warning(
                "Failed to read pstxnet file %s: %s — returning empty",
                file_path, exc,
            )
            return {}

        raw_connections: list[PstxnetConnection] = self._parse_content(content)
        result: dict[str, dict[str, str]] = self._group_by_refdes(raw_connections)
        # v2.1: Expand multi-section parts (U6 → U6A..U6I) so per-section
        # schematic instances can find their connections in this map.
        result = self._expand_sectioned_parts(file_path, result)
        logger.info(
            "PstxnetNetlistParser: %d connections → %d refdes parsed from %s",
            len(raw_connections), len(result), file_path.name,
        )
        return result

    # ------------------------------------------------------------------
    #  Internal parsing
    # ------------------------------------------------------------------

    @staticmethod
    def _parse_content(content: str) -> list[PstxnetConnection]:
        """Parse pstxnet.dat content using a state machine.

        The format has NET_NAME on one line and the quoted name on the
        next line.  NODE_NAME refdes pin are on a single line.

        State flow: IDLE → IN_NET_HEADER → IN_NET → IN_NODES → IDLE

        Args:
            content: Raw file content as a string.

        Returns:
            List of PstxnetConnection objects.
        """
        connections: list[PstxnetConnection] = []
        state: int = _IDLE
        current_net_name: str = ""

        for line in content.splitlines():
            stripped: str = line.strip()

            # Skip empty lines and comments/sub-lines
            if not stripped or stripped.startswith("{") or stripped.startswith("--"):
                continue

            # Skip known sub-lines (C_SIGNAL, DIFFERENTIAL_PAIR, etc.)
            if _RE_SKIP_LINE.match(stripped):
                continue

            # ── State: IN_NET_HEADER — looking for quoted net name ──
            if state == _IN_NET_HEADER:
                m_name = _RE_QUOTED_NAME.match(stripped)
                if m_name:
                    current_net_name = m_name.group(1)
                    state = _IN_NET
                    continue
                # Not a quoted name — reset
                state = _IDLE
                continue

            # ── Detect NET_NAME header ──
            m_net_hdr = _RE_NET_NAME_HEADER.match(stripped)
            if m_net_hdr:
                state = _IN_NET_HEADER
                current_net_name = ""
                continue

            # ── Detect NODE_NAME inside a net ──
            if state in (_IN_NET, _IN_NODES):
                m_node = _RE_NODE_NAME.match(stripped)
                if m_node:
                    refdes: str = m_node.group(1)
                    pin_num: str = m_node.group(2)
                    connections.append(PstxnetConnection(
                        refdes=refdes,
                        pin_number=pin_num,
                        net_name=current_net_name,
                    ))
                    state = _IN_NODES
                    continue

                # Non-node line while in net — may be sub-lines like
                # '@path...' or "'B':;" — keep state, try next line
                if stripped.startswith("@") or stripped.startswith("'"):
                    continue
                # Otherwise end of current net
                state = _IDLE
                current_net_name = ""

        return connections

    # ------------------------------------------------------------------
    #  Multi-section part expansion (v2.1)
    # ------------------------------------------------------------------

    @classmethod
    def _expand_sectioned_parts(
        cls,
        file_path: Path,
        netlist_map: dict[str, dict[str, str]],
    ) -> dict[str, dict[str, str]]:
        """Expand multi-section refdes (e.g. U6 → U6A..U6I) in the netlist map.

        OrCAD encodes a multi-section part as a *single* refdes (e.g. ``U6``)
        in pstxnet.dat, while the schematic/EDIF side references per-section
        instances (``U6A``..``U6I``).  Without expansion every per-section
        lookup misses and the whole part loses its connections.

        The section letters come from the sibling ``pstxprt.dat``
        (``SECTION='A'..'I'`` entries) and the pin→section assignment from
        the sibling ``pstchip.dat`` primitive's multi-position ``PIN_NUMBER``
        tuple ``'(BGA,secA,secB,...)'`` (position 1 = section A, ...).

        If sibling files are absent, or nothing is sectioned, the map is
        returned unchanged.

        Args:
            file_path: Path of the parsed pstxnet.dat file.
            netlist_map: refdes → {pin_number: net_name} map.

        Returns:
            A new map that also contains the expanded per-section refdes.
        """
        pstxprt_path = file_path.parent / "pstxprt.dat"
        pstchip_path = file_path.parent / "pstchip.dat"
        if not pstxprt_path.exists() or not pstchip_path.exists():
            return netlist_map

        try:
            from .pstxnet_parser import PstxnetParser
            from .pstchip_parser import PstchipParser
        except Exception as exc:  # pragma: no cover — defensive
            logger.debug("pstxnet section expansion unavailable: %s", exc)
            return netlist_map

        # ── 1. pstxprt: refdes → {section → primitive_name} ──────────
        xprt_ir = PstxnetParser().parse(pstxprt_path)
        entries = xprt_ir.metadata.get("pstxnet_entries", [])
        sectioned: dict[str, dict[str, str]] = {}
        for entry in entries:
            if not entry.section:
                continue
            sectioned.setdefault(entry.refdes.upper(), {})[
                entry.section.upper()
            ] = entry.part_name
        sectioned = {r: s for r, s in sectioned.items() if len(s) > 1}
        if not sectioned:
            return netlist_map

        # ── 2. pstchip: primitive_name → {bga_pin: [section letters]} ──
        chip_map = PstchipParser().parse(pstchip_path)
        primitive_sections: dict[str, dict[str, list[str]]] = {}
        for prim_name, chip_entry in chip_map.items():
            pin_secs = getattr(chip_entry, "pin_sections", {})
            if pin_secs:
                primitive_sections[prim_name] = pin_secs

        # ── 3. Distribute each pin to its section refdes ──────────────
        expanded: dict[str, dict[str, str]] = dict(netlist_map)
        distributed_pins = 0
        for refdes, sections in sectioned.items():
            pins = netlist_map.get(refdes)
            if not pins:
                continue
            # All section entries share the same primitive name.
            prim_name = next(iter(sections.values()))
            pin_sec_map = primitive_sections.get(prim_name)
            if not pin_sec_map:
                logger.debug(
                    "pstxnet: no pstchip pin_sections for %s (%s) — skipped",
                    refdes, prim_name,
                )
                continue
            for bga_pin, net_name in pins.items():
                letters = pin_sec_map.get(bga_pin)
                if not letters:
                    continue
                for letter in letters:
                    sub_refdes = f"{refdes}{letter}"
                    expanded.setdefault(sub_refdes, {})[bga_pin] = net_name
                    distributed_pins += 1

        if distributed_pins:
            logger.info(
                "pstxnet: expanded %d sectioned refdes → %d pins distributed "
                "to per-section instances (e.g. U6 → U6A..U6I)",
                len(sectioned), distributed_pins,
            )
        return expanded

    # ------------------------------------------------------------------
    #  Grouping helper
    # ------------------------------------------------------------------

    @staticmethod
    def _group_by_refdes(
        connections: list[PstxnetConnection],
    ) -> dict[str, dict[str, str]]:
        """Group connections by refdes into {refdes: {pin_number: net_name}}.

        Args:
            connections: Flat list of PstxnetConnection objects.

        Returns:
            Nested dict: refdes → {pin_number: net_name}.
        """
        result: dict[str, dict[str, str]] = {}
        for conn in connections:
            if conn.refdes not in result:
                result[conn.refdes] = {}
            result[conn.refdes][conn.pin_number] = conn.net_name
        return result
