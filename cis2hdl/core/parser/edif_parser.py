"""EDIF 2.0.0 S-expression parser — extracts logic netlist from OrCAD EDIF export.

Parses .edf files generated by OrCAD cap2edi into the unified DesignIR,
covering component definitions, instances, nets, and net classification.

Phase XI P0-A1/A4: EDIF **does** contain coordinates — ``(figure WIRE
(path (pointList (pt x y) ...)))`` polylines (verified on
HG5015-BE36_V10.EDF: 2516 wire figures / 4257 points / 836 of 862 nets
with geometry).  These are now extracted into ``NetIR.wires`` /
``PageIR.wires`` to drive CSA ``WIRE 16 -1`` generation.  Instance
coordinates are approximated from ``(designator (display (origin (pt x y))))``
labels.  The historical claim "Coordinates absent in EDIF" was incorrect.

Phase XI P0-A2: OrCAD cap2edi exports multi-sheet schematics as 24
``(page (rename &NN_NAME "NN-Name") (pageSize ...) (instance ...)
(net ...) ...)`` blocks that are direct children of the top cell's view
contents.  ``_parse_page`` now detects these blocks and splits them into
separate PageIRs (previously every sheet collapsed into ``PageIR[0]``),
reading ``pageSize``/``boundingBox`` for page width/height.  When a cell
has no page blocks the legacy ``_cell_is_page`` heuristic is used as a
fallback for other EDIF variants.

References:
    ORCAD_SOURCE_ANALYSIS.md §12 for the 12 structural rules
    BACKEND_DESIGN.md §3.0a for the EDIFParser interface
"""

